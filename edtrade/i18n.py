_language = DEFAULT_LANGUAGE


def set_language(code: str) -> str:
    """Ustaw język UI (nieznany kod → domyślny). Zwraca faktycznie ustawiony kod."""
    global _language
    _language = code if code in CATALOG else DEFAULT_LANGUAGE
    return _language


def get_language() -> str:
    return _language


def t(key: str, **values) -> str:
    """Tekst UI dla klucza w bieżącym języku, z podstawionymi {wartościami}."""
    text = CATALOG[_language].get(key) or CATALOG[DEFAULT_LANGUAGE].get(key, key)
    return text.format(**values) if values else text


def plural(n: int, key: str) -> str:
    """Forma słowa dla liczby n: '1 hop', '3 hopy', '5 hopów' / '1 hop', '3 hops'."""
    forms = t(key).split('|')
    one, few, many = (forms + forms[-1:] * 2)[:3]
    if n == 1:
        return one
    if _language == 'pl':
        return few if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14 else many
    return many
